CREATE INDEX idx_mpm_custom_match ON public.mmr_participant_metric USING btree (custom_match_id);
CREATE INDEX idx_mpm_guild_player ON public.mmr_participant_metric USING btree (guild_id, player_code);
CREATE INDEX idx_mpm_guild_season_played ON public.mmr_participant_metric USING btree (guild_id, season, played_date DESC);
CREATE INDEX idx_mpm_puuid_season ON public.mmr_participant_metric USING btree (puuid, season);