	takedowns_under_turret int4 NULL,
	takedowns_before_15min int4 NULL,
	jungle_cs_own int4 NULL,
	jungle_cs_enemy int4 NULL,
	damage_to_epic_monsters int4 NULL,
	objectives_stolen int4 NULL,
	barracks_killed int4 NULL,
